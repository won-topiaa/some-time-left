/**
 * 길찾기가 실패한 이유를 사람이 읽을 한 줄로.
 *
 * 화면에서 떼어 여기 둔다 — 화면 파일은 이 저장소의 테스트가 부를 수 없고(React
 * Native가 딸려 온다), 그래서 이 판단은 오래 시험되지 않은 채였다. 문장을 고르는
 * 일은 문장을 고르는 자리에서 시험할 수 있어야 한다.
 */

import { ApiError } from './http';

/**
 * 마지막 실패를 사람이 읽을 한 줄로.
 *
 * 기다리면 풀릴 일과 그렇지 않은 일을 나눈다. 도로가 없는 곳을 찍은 사람에게
 * "잠시 뒤에 다시 해볼까요?"라고 하면, 눌러도 같은 화면이 돌아오는 막다른 길이
 * 된다 — 이 앱에서 재시도 버튼은 정말 다시 해볼 만할 때만 뜻이 있다.
 */
export function routeFailureLine(failure: unknown): string {
  const message = failure instanceof Error ? failure.message : '';

  // 도로망이 그 근처를 아예 모른다. 다시 눌러도 같은 답이 온다.
  if (message.includes('걸을 수 있는 길이 없어요')) {
    return '그 근처에는 걸을 수 있는 길이 없어요.\n장소를 다시 골라볼까요?';
  }
  // 공급자가 길이라고 보기 어려운 좌표를 보냈다. 이것도 다시 부른다고 안 바뀐다.
  if (message.includes('걸을 수 있는 모양이 아니에요')) {
    return '길을 제대로 받지 못했어요.\n장소를 다시 골라볼까요?';
  }
  /*
   * 도로망이 대답은 했는데 그 대답이 '없다'였다 (`NoRoute`, `NoSegment` 같은 것들).
   *
   * 이 갈래가 없어서 그 대답까지 "잠시 뒤에 다시 해볼까요?"로 나갔다. 위 두 줄이
   * 막으려던 바로 그 막다른 길이다 — 눌러도 같은 화면이 돌아오고, 사람은 앱이
   * 고장 난 줄 안다. 기다림이 푸는 실패인지는 `ApiError`가 이미 알고 있으므로
   * 문구를 문자열로 짐작하지 않고 그걸 묻는다.
   *
   * `ApiError`가 아닌 실패는 우리가 모르는 것이다. 모르는 것을 두고 "장소를 다시"
   * 라고 하면 멀쩡한 목적지를 의심하게 만들므로, 그때는 다시 해보라고 둔다.
   */
  if (failure instanceof ApiError && !failure.retryable) {
    return '그 길은 찾지 못했어요.\n장소를 다시 골라볼까요?';
  }
  // 나머지는 대개 네트워크다. 그때는 정말 다시 해볼 만하다.
  return '길을 찾지 못했어요. 잠시 뒤에 다시 해볼까요?';
}
